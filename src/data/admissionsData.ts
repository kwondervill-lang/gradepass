// 9등급제 커트라인을 5등급제 환산 목표 등급으로 변환하는 연속 보간 함수
export function convert9To5Equivalent(grade9: number): number {
  const clamped = Math.max(1.0, Math.min(9.0, grade9));
  const anchorPoints: Array<[number, number]> = [
    [1.0, 1.0],
    [1.5, 1.0],
    [1.85, 1.2],
    [2.3, 1.5],
    [2.9, 2.0],
    [3.5, 2.4],
    [4.1, 2.7],
    [4.8, 3.0],
    [5.45, 3.35],
    [6.1, 3.7],
    [6.8, 4.0],
    [7.45, 4.35],
    [8.45, 5.0],
    [9.0, 5.0],
  ];

  if (clamped <= 1.15) return 1.0;
  if (clamped <= 1.5) {
    return Number((1.0 + ((clamped - 1.0) / 0.5) * 0.1).toFixed(2));
  }

  for (let i = 1; i < anchorPoints.length - 1; i++) {
    const [g9Prev, g5Prev] = anchorPoints[i];
    const [g9Next, g5Next] = anchorPoints[i + 1];
    if (clamped >= g9Prev && clamped <= g9Next) {
      const ratio = (clamped - g9Prev) / (g9Next - g9Prev);
      const interpolated = g5Prev + ratio * (g5Next - g5Prev);
      return Number(interpolated.toFixed(2));
    }
  }
  return 5.0;
}

